    if df is None or df.empty:
        raise ValueError("Cannot generate PDF: employee dataframe is empty.")

    work = df.copy()
    if "RiskPercentage" not in work.columns:
        raise ValueError("Cannot generate PDF: RiskPercentage column is missing.")

    work["RiskPercentage"] = pd.to_numeric(work["RiskPercentage"], errors="coerce")

    overall_risk = float(work["RiskPercentage"].mean())
    critical_emps = int((work["RiskPercentage"] > 75).sum())
    if "Attrition" in work.columns:
        predicted_attrition = int((work["Attrition"] == 1).sum())
    else:
        predicted_attrition = int((work["RiskPercentage"] > 80).sum())
