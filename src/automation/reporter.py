def send_executive_email(smtp_host, smtp_port, smtp_user, smtp_pass, target_email, attachment_bytes, attachment_name="Executive_Action_Plan.docx"):
    msg = EmailMessage()
    msg['Subject'] = 'Executive Review Required: Q3 Attrition Risk Forecast'
    msg['From'] = smtp_user
    msg['To'] = target_email

    msg.set_content(
        "Please find attached the autonomous AI-generated Executive Action Plan detailing the Q3 attrition risk forecast and mitigation strategies.\\n\\n"
        "Best regards,\\nPeopleRisk AI Agent"
    )

    msg.add_attachment(
        attachment_bytes,
        maintype='application',
        subtype='vnd.openxmlformats-officedocument.wordprocessingml.document',
        filename=attachment_name
    )

    import ssl
    context = ssl.create_default_context()
    
    if smtp_port == 465:
        with smtplib.SMTP_SSL(smtp_host, smtp_port, context=context, timeout=15) as server:
            server.login(smtp_user, smtp_pass)
            server.send_message(msg)
    else:
        with smtplib.SMTP(smtp_host, smtp_port, timeout=15) as server:
            server.starttls(context=context)
            server.login(smtp_user, smtp_pass)
            server.send_message(msg)
